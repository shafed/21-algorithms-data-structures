package block5.practice23;

// Очередь FIFO: элементы извлекаются в том же порядке, в котором были добавлены.
public interface Queue {

  // Предусловие: если вместимость ограничена, в очереди есть свободное место.
  // Постусловие: value добавлен в конец, размер увеличился на один.
  // Если очередь полна, выбрасывается IllegalStateException.
  void enqueue(Object value);

  // Предусловие: очередь непуста, иначе выбрасывается NoSuchElementException.
  // Постусловие: возвращён первый элемент, очередь не изменилась.
  Object element();

  // Предусловие: очередь непуста, иначе выбрасывается NoSuchElementException.
  // Постусловие: первый элемент удалён и возвращён, размер уменьшился на один.
  Object dequeue();

  // Возвращает число элементов. Очередь не меняется.
  int size();

  // Возвращает true, если очередь пуста. Очередь не меняется.
  boolean isEmpty();

  // Удаляет все элементы. После вызова размер равен нулю.
  void clear();
}
